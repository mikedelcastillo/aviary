# --------------------------------------------------------------------------- .env loading


def test_env_file_missing_is_noop(monkeypatch, missing_env):
    # A nonexistent --env-file must not error: load_env_file short-circuits on a missing path.
    assert not missing_env.exists()
    args = _parse(monkeypatch, env_file=missing_env)
    # parse succeeded and the path round-trips
    assert args.env_file == missing_env


def test_env_file_is_loaded_into_environ(monkeypatch, tmp_path):
    # parse_args loads the .env first via load_env_file; values land in os.environ (setdefault),
    # so a threshold written into the env file becomes the parsed default.
    monkeypatch.delenv("IMMICH_BIRD_THRESHOLD", raising=False)
    env_file = tmp_path / "real.env"
    env_file.write_text("IMMICH_BIRD_THRESHOLD=0.75\n", encoding="utf-8")
    argv = ["generate-albums", "--env-file", str(env_file)]
    monkeypatch.setattr(sys, "argv", argv)
    args = cli.parse_args()
    assert args.threshold == 0.75



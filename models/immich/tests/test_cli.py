# --------------------------------------------------------------------------- asset dedup


def test_dedupe_by_id_drops_duplicates_keeping_first():
    # Immich pagination can yield the same asset twice if the library mutates mid-scan; deduping
    # before the scan partition keeps each id from being enqueued (and its thumbnail raced) twice.
    assets = [
        {"id": "a", "originalFileName": "first.jpg"},
        {"id": "b", "originalFileName": "b.jpg"},
        {"id": "a", "originalFileName": "second.jpg"},
    ]
    deduped = cli.dedupe_by_id(assets)
    assert [a["id"] for a in deduped] == ["a", "b"]
    # First occurrence wins, not the later duplicate.
    assert deduped[0]["originalFileName"] == "first.jpg"


def test_dedupe_by_id_preserves_order_when_no_duplicates():
    assets = [{"id": "x"}, {"id": "y"}, {"id": "z"}]
    assert cli.dedupe_by_id(assets) == assets


def test_dedupe_by_id_coerces_ids_to_str_like_state_keys():
    # State and assets_by_id are keyed by str(asset["id"]); the dedup must match that coercion so
    # an int and its string form collapse to one entry.
    assets = [{"id": 5}, {"id": "5"}]
    assert cli.dedupe_by_id(assets) == [{"id": 5}]



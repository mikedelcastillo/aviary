def test_importing_cli_does_not_pull_gpu_stack():
    # Robust regardless of test order / what else has been imported in this process: a clean
    # subprocess proves importing the CLI alone never imports torch or cv2.
    repo_root = Path(__file__).resolve().parents[3]
    src_dir = repo_root / "models" / "immich"
    env = dict(os.environ)
    # The source tree must be importable in the child interpreter; mirror pyproject's pythonpath.
    env["PYTHONPATH"] = str(src_dir) + os.pathsep + env.get("PYTHONPATH", "")
    result = subprocess.run(
        [
            sys.executable,
            "-c",
            "import sys; import aviary_immich.cli; "
            "assert 'torch' not in sys.modules and 'cv2' not in sys.modules",
        ],
        cwd=str(repo_root),
        env=env,
        capture_output=True,
        text=True,
    )
    assert result.returncode == 0, f"stdout={result.stdout!r} stderr={result.stderr!r}"

"""Tests for ``aviary_immich.cli`` argument parsing and shell wiring.

``main()`` needs a live Immich server + GPU, so it is never invoked here. We exercise
``parse_args()`` (driven via ``sys.argv``) and the lazy-import discipline that keeps importing
the CLI from pulling in the GPU/ML stack.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

import aviary_immich.cli as cli


# --------------------------------------------------------------------------- helpers


def _parse(monkeypatch, *extra_args, env_file: Path):
    """Run ``parse_args`` with a controlled argv.

    Always pass ``--env-file`` pointing at a nonexistent path so ``load_env_file`` is a no-op
    and the test does not depend on a real ``.env``.
    """
    argv = ["generate-albums", "--env-file", str(env_file), *extra_args]
    monkeypatch.setattr(sys, "argv", argv)
    return cli.parse_args()


@pytest.fixture
def missing_env(tmp_path):
    """A path under tmp that does not exist, so ``load_env_file`` short-circuits."""
    return tmp_path / "does-not-exist.env"


